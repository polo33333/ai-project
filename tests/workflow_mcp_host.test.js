'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const http = require('node:http');
const crypto = require('node:crypto');
const { Client } = require('@modelcontextprotocol/sdk/client/index.js');
const { StreamableHTTPClientTransport } = require('@modelcontextprotocol/sdk/client/streamableHttp.js');

test('hosted MCP UI settings, bearer access, OAuth PKCE, refresh and revocation', async t => {
  process.env.BOOTSTRAP_ADMIN_PASSWORD = 'hosted-mcp-test-password';
  const auth = require('../src/backend/services/auth_service');
  const { handleRequest } = require('../src/backend/routes/router');
  const storageHttp = require('../src/backend/storage/http');
  const app = http.createServer((req, res) => storageHttp.handleStoredRequest(req, res, handleRequest).catch(error => { res.writeHead(500); res.end(JSON.stringify({ error: error.message })); }));
  await new Promise(resolve => app.listen(0, '127.0.0.1', resolve));
  t.after(() => { app.closeAllConnections(); return new Promise(resolve => app.close(resolve)); });
  const base = `http://127.0.0.1:${app.address().port}`, endpoint = base + '/mcp/workflows';
  const login = await fetch(base + '/api/auth/login', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ username: 'admin', password: process.env.BOOTSTRAP_ADMIN_PASSWORD }) });
  const cookie = login.headers.get('set-cookie').split(';')[0];
  const request = (route, method = 'GET', body, authenticated = true) => fetch(base + route, { method, headers: { 'Content-Type': 'application/json', ...(authenticated ? { Cookie: cookie } : {}) }, ...(body === undefined ? {} : { body: JSON.stringify(body) }) });
  assert.equal((await request('/api/workflow-plugins/mcp', 'GET', undefined, false)).status, 401);
  assert.equal((await request('/mcp/workflows', 'POST', {}, false)).status, 503);
  assert.equal((await request('/api/workflow-plugins/mcp', 'PUT', { enabled: true, publicOrigin: 'http://remote.test', revision: null })).status, 400);
  const save = await request('/api/workflow-plugins/mcp', 'PUT', { enabled: true, publicOrigin: base, revision: null });
  assert.equal(save.status, 200, await save.clone().text());
  let settings = (await save.json()).settings;
  const missing = await request('/mcp/workflows', 'POST', {}, false);
  assert.equal(missing.status, 401);
  assert.ok(missing.headers.get('www-authenticate').includes('resource_metadata'));
  const metadata = await (await request('/.well-known/oauth-authorization-server', 'GET', undefined, false)).json();
  assert.equal(metadata.issuer, base);
  assert.deepEqual(metadata.code_challenge_methods_supported, ['S256']);
  const generated = await (await request('/api/workflow-plugins/mcp/tokens', 'POST', { label: 'Codex', days: 7 })).json();
  assert.ok(generated.token.startsWith('kh_mcp_'));
  const listed = await (await request('/api/workflow-plugins/mcp')).json();
  assert.equal(listed.connections.length, 1);
  assert.ok(!JSON.stringify(listed).includes(generated.token));
  assert.ok(!JSON.stringify(await require('../src/backend/automation').repository.list('catalog')).includes(generated.token));
  const connect = async token => {
    const client = new Client({ name: 'hosted-test', version: '1.0.0' });
    t.after(() => client.close());
    await client.connect(new StreamableHTTPClientTransport(new URL(endpoint), { requestInit: { headers: { Authorization: 'Bearer ' + token } } }));
    return client;
  };
  const client = await connect(generated.token);
  assert.equal((await client.listTools()).tools.length, 7);
  const guide = JSON.parse((await client.callTool({ name: 'workflow_guide', arguments: {} })).content[0].text);
  guide.example.manifest.id = 'hosted_mcp_example';
  const saved = await client.callTool({ name: 'workflow_save_draft', arguments: { bundle: guide.example, revision: null } });
  assert.equal(saved.isError, undefined, JSON.stringify(saved));
  assert.equal(JSON.parse(saved.content[0].text).package.createdBy, 'admin');
  assert.equal((await client.callTool({ name: 'workflow_catalog', arguments: {} })).isError, undefined);
  await request('/api/workflow-plugins/mcp/revoke', 'POST', { id: generated.connection.id });
  await assert.rejects(client.listTools());

  const redirect = 'https://client.example/callback';
  const registration = await (await request('/mcp/workflows/register', 'POST', { client_name: '<Claude>', redirect_uris: [redirect], token_endpoint_auth_method: 'none' }, false)).json();
  const verifier = crypto.randomBytes(32).toString('base64url');
  const params = new URLSearchParams({ client_id: registration.client_id, redirect_uri: redirect, response_type: 'code', code_challenge_method: 'S256',
    code_challenge: crypto.createHash('sha256').update(verifier).digest('base64url'), state: 'test-state', resource: endpoint });
  const badRedirect = new URLSearchParams(params); badRedirect.set('redirect_uri', 'https://evil.example/callback');
  assert.equal((await request('/mcp/workflows/authorize?' + badRedirect, 'GET', undefined, false)).status, 400);
  const page = await (await request('/mcp/workflows/authorize?' + params, 'GET', undefined, false)).text();
  assert.ok(page.includes('&lt;Claude&gt;'));
  assert.ok(page.includes('Cho phép kết nối'));
  assert.ok(page.includes('https://client.example'));
  const pendingId = page.match(/const requestId="([^"]+)"/)[1];
  const authorize = '/api/workflow-plugins/mcp/authorize';
  assert.equal((await request(authorize, 'POST', { requestId: pendingId, approve: true }, false)).status, 401);
  const approval = await (await request(authorize, 'POST', { requestId: pendingId, approve: true })).json();
  const callback = new URL(approval.redirect);
  assert.equal(callback.origin, 'https://client.example');
  assert.equal(callback.searchParams.get('state'), 'test-state');
  assert.equal((await request(authorize, 'POST', { requestId: pendingId, approve: true })).status, 400);
  const tokenRequest = body => fetch(base + '/mcp/workflows/token', { method: 'POST', headers: { 'Content-Type': 'application/x-www-form-urlencoded' }, body: new URLSearchParams(body) });
  const grant = { grant_type: 'authorization_code', code: callback.searchParams.get('code'), client_id: registration.client_id, redirect_uri: redirect, code_verifier: verifier, resource: endpoint };
  assert.equal((await tokenRequest({ ...grant, code_verifier: 'wrong' })).status, 400);
  const tokenResponse = await tokenRequest(grant);
  assert.equal(tokenResponse.status, 200, await tokenResponse.clone().text());
  const tokens = await tokenResponse.json();
  assert.equal((await tokenRequest(grant)).status, 400);
  const oauthClient = await connect(tokens.access_token);
  assert.equal((await oauthClient.listTools()).tools.length, 7);
  const refreshGrant = { grant_type: 'refresh_token', refresh_token: tokens.refresh_token, client_id: registration.client_id, resource: endpoint };
  const refreshed = await (await tokenRequest(refreshGrant)).json();
  assert.ok(refreshed.access_token);
  assert.equal((await tokenRequest(refreshGrant)).status, 400);
  const refreshedClient = await connect(refreshed.access_token);
  const connections = (await (await request('/api/workflow-plugins/mcp')).json()).connections;
  const oauthConnection = connections.find(item => item.clientId === registration.client_id);
  assert.equal(connections.filter(item => item.clientId === registration.client_id).length, 1);
  await request('/api/workflow-plugins/mcp/revoke', 'POST', { id: oauthConnection.id });
  await assert.rejects(refreshedClient.listTools());
  assert.equal((await tokenRequest({ ...refreshGrant, refresh_token: refreshed.refresh_token })).status, 400);
  const another = await (await request('/api/workflow-plugins/mcp/tokens', 'POST', { label: 'role test' })).json();
  const roleClient = await connect(another.token);
  const owner = auth.accounts.find(account => account.id === 'admin');
  owner.role = 'user';
  await assert.rejects(roleClient.listTools());
  assert.equal((await request('/api/workflow-plugins/mcp')).status, 403);
  owner.role = 'admin';
  settings = (await (await request('/api/workflow-plugins/mcp')).json()).settings;
  assert.equal((await request('/api/workflow-plugins/mcp', 'PUT', { enabled: false, publicOrigin: base, revision: settings.revision })).status, 200);
  assert.equal((await request('/mcp/workflows', 'POST', {}, false)).status, 503);
});
